/** Cells flagging a problem render in --bad-ink (README: "so the exceptions
 * are findable without reading every row"). */
export function panelCellIsFlag(text: string): "bad" | "warn" | null {
  if (/No match|needs|Missing|Blocking|Overdue|Duplicate|Not set|No contract|breached/.test(text)) return "bad";
  if (/Not assigned|Not uploaded/.test(text)) return "warn";
  return null;
}
