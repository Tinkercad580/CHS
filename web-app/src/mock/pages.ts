import type { ColSpec, PageSpec, Row } from "../lib/types";

function cols(a: string, b: string, c: string, d: string, e: string, f: string): PageSpec["cols"] {
  const mk = (label: string, align: "left" | "right"): ColSpec => ({ label, align });
  return [mk(a, "left"), mk(b, "left"), mk(c, "left"), mk(d, "left"), mk(e, "right"), mk(f, "right")];
}

function r(a: string, b: string, c: string, d: string, e: string, pill: string, k: Row["k"], eFg?: string): Row {
  return { a, b, c, d, e, pill, k, eFg: eFg ?? "var(--ink,#0F1A17)" };
}

